    # ============================================================ timing ====
    def play(self, *animations, **kwargs):
        if kwargs.get("run_time") is not None:
            kwargs["run_time"] *= TIME_SCALE
        return super().play(*animations, **kwargs)

    def wait(self, duration=DEFAULT_WAIT_TIME, *args, **kwargs):
        return super().wait(duration * TIME_SCALE, *args, **kwargs)

    def read_wait(self, *texts: str, minimum=2.0, extra=0.0):
        """Protocol reading rule: ≥ 0.35 s per new word, at least 2 s."""
        n = sum(words_in(t) for t in texts)
        self.wait(max(minimum, 0.35 * n) + extra)

    # ======================================================= primitives ====
    def txt(self, content, size=24, weight=NORMAL, color=INK, slant=NORMAL):
        t = Text(content, font=FONT, font_size=size, weight=weight, color=color,
                 slant=slant, line_spacing=0.9)
        t._fs, t._w0, t._h0, t._rot, t._kind = size, t.width, t.height, False, "text"
        return t

    def math(self, expr, size=34, color=INK):
        m = MathTex(expr, font_size=size, color=color)
        m._fs, m._w0, m._h0, m._rot, m._kind = size, m.width, m.height, False, "math"
        return m

    def wrap(self, text, size=24, max_w=6.4, weight=NORMAL, color=INK, buff=0.12):
        """Greedy word wrap with measured glyph widths (never shrinks text)."""
        lines, cur = [], ""
        for word in text.split(" "):
            trial = (cur + " " + word).strip()
            if cur and self.txt(trial, size, weight).width > max_w:
                lines.append(cur)
                cur = word
            else:
                cur = trial
        if cur:
            lines.append(cur)
        g = VGroup(*[self.txt(l, size, weight, color) for l in lines])
        g.arrange(DOWN, aligned_edge=LEFT, buff=buff)
        return g

    def panel(self, spec, stroke=RULE):
        return RoundedRectangle(width=spec["w"], height=spec["h"], corner_radius=0.16,
                                stroke_color=stroke, stroke_width=2,
                                fill_color=BG, fill_opacity=1).move_to(spec["center"])

    def card(self, content, pad=0.26, stroke=STROKE, fill=BG, width=None, sw=1.8):
        w = (width if width is not None else content.width + 2 * pad)
        box = RoundedRectangle(width=w, height=content.height + 2 * pad,
                               corner_radius=0.12, stroke_color=stroke, stroke_width=sw,
                               fill_color=fill, fill_opacity=1).move_to(content)
        if width is not None:
            content.align_to(box, LEFT).shift(RIGHT * pad)
        return VGroup(box, content)

