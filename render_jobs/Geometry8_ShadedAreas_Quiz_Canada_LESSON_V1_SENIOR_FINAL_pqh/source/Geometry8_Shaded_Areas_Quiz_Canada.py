    # ======================================================== QA hooks ====
    def qa_event(self, label: str):
        prob = getattr(self, "_qa_problem", "global")
        safe = "".join(ch if ch.isalnum() else "_" for ch in label).strip("_")
        t = float(self.renderer.time)
        self.qa_events.append((prob, safe, t))
        fails = self.audit_frame()
        for f in fails:
            self.qa_fails.append(f"{prob}|{safe}|{t:.2f}|{f}")
        print(f"QA_EVENT|{prob}|{safe}|{t:.3f}|fails={len(fails)}", flush=True)

    def _texts(self):
        out = []
        for top in self.mobjects:
            for m in top.get_family():
                if isinstance(m, (Text, MathTex)) and hasattr(m, "_fs"):
                    op = max((sm.get_fill_opacity() for sm in m.family_members_with_points()),
                             default=0)
                    if op > 0.05:
                        out.append(m)
        return out

    def audit_frame(self):
        fails = []
        texts = self._texts()
        boxes = []
        for m in texts:
            w0, h0 = (m._h0, m._w0) if m._rot else (m._w0, m._h0)
            scale = max(m.width / w0 if w0 else 1, m.height / h0 if h0 else 1)
            eff = m._fs * scale
            floor = TEXT_FLOOR if m._kind == "text" else MATH_FLOOR
            name = (m.text if isinstance(m, Text) else m.get_tex_string())[:28]
            if eff < floor - 0.5:
                fails.append(f"FONT {eff:.1f}<{floor} '{name}'")
            l, r = m.get_left()[0], m.get_right()[0]
            b, t = m.get_bottom()[1], m.get_top()[1]
            if l < -SAFE_X or r > SAFE_X or b < -SAFE_Y or t > SAFE_Y:
                fails.append(f"SAFE '{name}'")
            if not getattr(m, "_qa_exempt", False):
                boxes.append((l, r, b, t, name))
        tol = 0.02
        for i in range(len(boxes)):
            for j in range(i + 1, len(boxes)):
                a, c = boxes[i], boxes[j]
                if (min(a[1], c[1]) - max(a[0], c[0]) > tol and
                        min(a[3], c[3]) - max(a[2], c[2]) > tol):
                    fails.append(f"OVERLAP '{a[4]}' x '{c[4]}'")
        return fails

    # ====================================================== the figure ====
    def build_figure(self, prob: Problem, spec, margin=0.55):
        """Draw a problem in frame units, fitted inside a panel.

        Returns a dict with the pieces the beats animate.  Labels keep their
        size; only the geometry scale `s` adapts to the panel.
        """
        x0, y0, x1, y1 = prob.bounds()
        pts = [(x0, y0), (x1, y1)]
        for d in prob.dims:
            pts += [d.p1, d.p2] if d.kind != "text" else [d.p1]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        mx0, mx1, my0, my1 = min(xs), max(xs), min(ys), max(ys)
        avail_w, avail_h = spec["w"] - 2 * margin, spec["h"] - 2 * margin
        s = min(avail_w / (mx1 - mx0), avail_h / (my1 - my0))
        for _ in range(6):
            fig = self._draw_figure(prob, s, ((mx0 + mx1) / 2, (my0 + my1) / 2))
            g = fig["all"]
            if g.width <= spec["w"] - 0.30 and g.height <= spec["h"] - 0.30:
                break
            s *= min((spec["w"] - 0.30) / g.width, (spec["h"] - 0.30) / g.height) * 0.98
        shift = spec["center"] - g.get_center()
        g.shift(shift)
        for hv in fig["hi"].values():
            hv.shift(shift)
        fig["origin"] = fig["origin"] + shift
        fig["s"] = s
        return fig

    def _draw_figure(self, prob: Problem, s, model_center):
        mcx, mcy = model_center
        origin = np.array([0.0, 0.0, 0.0])

        def F(pt):
            return origin + np.array([s * (pt[0] - mcx), s * (pt[1] - mcy), 0.0])

        def mob_for(shape, fill, fill_op, stroke_w, stroke_c=INK):
            k, p = shape.kind, shape.params
            kw = dict(fill_color=fill, fill_opacity=fill_op,
                      stroke_color=stroke_c, stroke_width=stroke_w)
            if k == "rect":
                xa, ya, xb, yb = p
                return Polygon(F((xa, ya)), F((xb, ya)), F((xb, yb)), F((xa, yb)), **kw)
            if k in ("tri", "poly"):
                return Polygon(*[F(v) for v in p], **kw)
            if k == "circle":
                cx, cy, r = p
                return Circle(radius=r * s, **kw).move_to(F((cx, cy)))
            if k == "semicircle":
                cx, cy, r, start = p
                return Sector(radius=r * s, angle=PI, start_angle=math.radians(start),
                              arc_center=F((cx, cy)), **kw)
            raise ValueError(k)

        parts, gaps_hi, pos_fill = {}, {}, VGroup()
        for part in prob.parts:
            if part.sign > 0:
                g = VGroup(*[mob_for(sh, SHADE, 1, 0) for sh in part.shapes])
                pos_fill.add(*g)
            else:
                g = VGroup(*[mob_for(sh, BG, 1, 2.6) for sh in part.shapes])
            parts[part.key] = g
            gaps_hi[part.key] = VGroup(*[
                mob_for(sh, FOCUS if part.sign > 0 else BG, 1, 5.0) for sh in part.shapes
            ])

        # silhouette of the union of positive shapes
        sil_poly = unary_union([sh.poly() for p in prob.positives for sh in p.shapes])
        coords = list(sil_poly.exterior.coords)
        sil = VMobject(stroke_color=INK, stroke_width=3)
        sil.set_points_as_corners([F(c) for c in coords])

        seams = VGroup(*[DashedLine(F(a), F(b), color=STROKE, stroke_width=3.0,
                                    dash_length=0.10) for a, b in prob.seams])

        dims = VGroup()
        for d in prob.dims:
            if d.kind == "arrow":
                arr = DoubleArrow(F(d.p1), F(d.p2), buff=0, stroke_width=2.2, color=STROKE,
                                  tip_length=0.15, max_tip_length_to_length_ratio=0.25)
                lab = self.txt(d.text, 22, BOLD)
                if d.rotate:
                    lab.rotate(PI / 2)
                    lab._rot = True
                lab.move_to(arr.get_center() + np.array([d.offset[0], d.offset[1], 0]))
                ticks = VGroup()
                dims.add(VGroup(arr, lab, ticks))
            elif d.kind == "text":
                dims.add(self.txt(d.text, 22, BOLD).move_to(F(d.p1)))
            elif d.kind == "radius":
                ln = Line(F(d.p1), F(d.p2), color=INK, stroke_width=2.4)
                dot = Dot(F(d.p1), radius=0.045, color=INK)
                lab = self.txt(d.text, 22, BOLD).move_to(
                    F(d.p1) + np.array([d.offset[0], d.offset[1], 0]))
                dims.add(VGroup(ln, dot, lab))

        tags = {}
        for part in prob.parts:
            spots = [part.tag_at]
            if len(part.shapes) > 1:          # symmetric pieces (two semicircles)
                spots.append((2 * mcx - part.tag_at[0] if False else -part.tag_at[0],
                              part.tag_at[1]))
            tg = VGroup()
            for sp in spots:
                lab = self.txt(part.key, 20, BOLD)
                badge = self.sign_badge(part.sign, 0.15)
                row = VGroup(lab, badge).arrange(RIGHT, buff=0.06).move_to(F(sp))
                tg.add(row)
            tags[part.key] = tg

        gap_mobs = VGroup(*[parts[p.key] for p in prob.negatives])
        geometry = VGroup(pos_fill, sil, gap_mobs)
        everything = VGroup(geometry, seams, dims, *tags.values())
        return dict(all=everything, geometry=geometry, parts=parts, hi=gaps_hi,
                    sil=sil, seams=seams, dims=dims, tags=tags, origin=origin)

