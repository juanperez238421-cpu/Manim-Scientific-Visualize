    def toolbox(self):
        self.next_section("toolbox")
        self.set_header("02", "FORMULA TOOLBOX",
                        "You will need these six area formulas. Use the radius, not the "
                        "diameter, for circles.")
        k = 0.30

        def mk(kind):
            kw = dict(stroke_color=INK, stroke_width=2.6, fill_color=SHADE, fill_opacity=1)
            if kind == "rect":
                return Rectangle(width=5 * k, height=3 * k, **kw)
            if kind == "square":
                return Square(side_length=3.3 * k, **kw)
            if kind == "tri":
                return Polygon(LEFT * 2.5 * k + DOWN * 1.5 * k, RIGHT * 2.5 * k + DOWN * 1.5 * k,
                               RIGHT * 0.7 * k + UP * 1.5 * k, **kw)
            if kind == "rhombus":
                return Polygon(LEFT * 2.4 * k, UP * 1.6 * k, RIGHT * 2.4 * k, DOWN * 1.6 * k, **kw)
            if kind == "circle":
                return Circle(radius=1.6 * k, **kw)
            return Sector(radius=2.1 * k, angle=PI, start_angle=0, **kw).move_to(ORIGIN)

        data = [("RECTANGLE", "rect", r"A=b\times h"),
                ("SQUARE", "square", r"A=s^2"),
                ("TRIANGLE", "tri", r"A=\frac{b\times h}{2}"),
                ("RHOMBUS", "rhombus", r"A=\frac{D\times d}{2}"),
                ("CIRCLE", "circle", r"A=\pi r^2"),
                ("SEMICIRCLE", "semi", r"A=\frac{\pi r^2}{2}")]
        cards = VGroup()
        for name, kind, eq in data:
            icon = mk(kind)
            icon_box = Rectangle(width=2.0, height=1.15, stroke_width=0, fill_opacity=0)
            icon.move_to(icon_box)
            content = VGroup(self.txt(name, 24, BOLD), VGroup(icon_box, icon),
                             self.math(eq, 40)).arrange(DOWN, buff=0.18)
            box = RoundedRectangle(width=4.75, height=3.05, corner_radius=0.12,
                                   stroke_color=STROKE, stroke_width=1.8,
                                   fill_color=BG, fill_opacity=1)
            content.move_to(box)
            cards.add(VGroup(box, content))
        cards.arrange_in_grid(rows=2, cols=3, buff=(0.34, 0.30)).move_to(DOWN * 0.80)
        self.play(LaggedStart(*[FadeIn(c, shift=UP * 0.1) for c in cards], lag_ratio=0.12),
                  run_time=RUN_SLOW * 1.8)
        self.qa_event("toolbox")
        self.wait(PAUSE_WORK + PAUSE_EXPLAIN)
        self.clear_all()

    # ===================================================== one problem ====
    def problem_statement(self, prob: Problem, num: str):
        self.next_section(f"problem_{prob.number}")
        self._qa_problem = prob.slug
        self.set_header(num, f"PROBLEM {prob.number} · {prob.title}",
                        f"{prob.level.title()}. Read the problem and study the figure.")
        lp, rp = self.panel(LEFT_PANEL), self.panel(RIGHT_PANEL)
        fig = self.build_figure(prob, LEFT_PANEL)
        self.play(FadeIn(lp), FadeIn(rp), run_time=RUN_QUICK)
        self.play(FadeIn(fig["geometry"]), run_time=RUN_SLOW)
        self.play(FadeIn(fig["dims"]), run_time=RUN_NORMAL)

        body = self.wrap(prob.statement, 24, RIGHT_PANEL["w"] - 0.70)
        find = self.wrap(prob.find_text, 24, RIGHT_PANEL["w"] - 0.70, BOLD)
        stmt = VGroup(body, find).arrange(DOWN, aligned_edge=LEFT, buff=0.22)
        top = RIGHT_PANEL["center"][1] + RIGHT_PANEL["h"] / 2 - 0.30
        stmt.move_to(RIGHT_PANEL["center"]).align_to(
            np.array([0, top, 0]), UP).align_to(rp, LEFT).shift(RIGHT * 0.34)
        self.play(FadeIn(body, shift=UP * 0.05), run_time=RUN_SLOW)
        self.play(FadeIn(find), run_time=RUN_QUICK)
        self.qa_event("statement")
        self.read_wait(prob.statement, extra=PAUSE_EXPLAIN)

        # ---- PAUSE · SOLVE IT with a visible timer -------------------------
        head = VGroup(self.txt("PAUSE · SOLVE IT", 26, BOLD),
                      self.txt("Pause the video now and solve on paper.", 22)
                      ).arrange(DOWN, aligned_edge=LEFT, buff=0.12)
        bar_w = RIGHT_PANEL["w"] - 1.30
        track = Rectangle(width=bar_w, height=0.20, stroke_color=STROKE, stroke_width=1.5,
                          fill_color=FILL, fill_opacity=1)
        content = VGroup(head, track).arrange(DOWN, aligned_edge=LEFT, buff=0.18)
        solve = self.card(content, pad=0.20, stroke=INK, sw=2.4, width=RIGHT_PANEL["w"] - 0.60)
        bottom = RIGHT_PANEL["center"][1] - RIGHT_PANEL["h"] / 2 + 0.28
        solve.move_to(np.array([RIGHT_PANEL["center"][0], bottom + solve.height / 2, 0]))
        if solve.get_top()[1] > stmt.get_bottom()[1] - 0.12:
            print(f"LAYOUT WARNING: solve card overlaps statement in P{prob.number}")
        tracker = ValueTracker(1.0)
        left_x = track.get_left()

        def bar():
            w = max(0.001, bar_w * tracker.get_value())
            return Rectangle(width=w, height=0.20, stroke_width=0, fill_color=INK,
                             fill_opacity=1).move_to(left_x + RIGHT * w / 2)

        fill_bar = always_redraw(bar)
        self.play(FadeIn(solve), FadeIn(fill_bar), run_time=RUN_NORMAL)
        self.qa_event("solve_pause")
        self.play(tracker.animate.set_value(0.0), run_time=PAUSE_SOLVE, rate_func=linear)
        fill_bar.clear_updaters()
        self.wait(PAUSE_SHORT)
        self.play(FadeOut(solve), FadeOut(fill_bar), FadeOut(stmt), run_time=RUN_NORMAL)
        return fig, lp, rp

    def spotlight_on(self, fig, key):
        veil = Rectangle(width=LEFT_PANEL["w"] - 0.08, height=LEFT_PANEL["h"] - 0.08,
                         stroke_width=0, fill_color=BG, fill_opacity=0.80
                         ).move_to(LEFT_PANEL["center"]).set_z_index(5)
        hi = fig["hi"][key].copy().set_z_index(6)
        tag = fig["tags"][key].copy().set_z_index(7)
        for m in tag.get_family():
            m._qa_exempt = True
        self.play(FadeIn(veil), FadeIn(hi), FadeIn(tag), run_time=RUN_NORMAL)
        return VGroup(veil, hi, tag)

    def ledger_row(self, part):
        badge = self.sign_badge(part.sign, 0.17)
        eq = self.math(f"A_{{{part.key[1:]}}}={part.value.latex()}" + r"\ \text{cm}^2", 32)
        return VGroup(badge, eq).arrange(RIGHT, buff=0.16)

    def solution(self, prob: Problem, num: str, fig, lp, rp):
        self.next_section(f"solution_{prob.number}")
        self.set_header(num, f"SOLUTION {prob.number} · {prob.title}",
                        "Step 1 of 4 · IDENTIFY: name every figure and decide if it adds (+) "
                        "or is removed (−).")
        rx = rp.get_left()[0] + 0.34
        rtop = rp.get_top()[1] - 0.30

        # ---------------- STEP 1 · IDENTIFY ---------------------------------
        self.play(Create(fig["seams"]), run_time=RUN_NORMAL)
        self.qa_event("decomposition")
        for part in prob.parts:
            # highlight a COPY: animating the part itself would re-add it on top
            # of the white gaps (ManimCE moves animated submobjects to the front).
            flash = fig["hi"][part.key].copy().set_z_index(3)
            fig["tags"][part.key].set_z_index(4)
            self.play(FadeIn(flash), run_time=RUN_QUICK)
            self.play(FadeIn(fig["tags"][part.key], scale=0.8), run_time=RUN_QUICK)
            self.wait(PAUSE_SHORT)
            self.play(FadeOut(flash), run_time=RUN_QUICK)
        rows = VGroup()
        for part in prob.parts:
            rows.add(VGroup(self.sign_badge(part.sign, 0.17),
                            self.txt(part.key, 23, BOLD),
                            self.txt(part.describe.replace("  ", " · "), 22)
                            ).arrange(RIGHT, buff=0.18))
        rows.arrange(DOWN, aligned_edge=LEFT, buff=0.24)
        plan_title = self.txt("PLAN", 24, BOLD, MUTED)
        plan = self.math(prob.plan_latex(), 36)
        plan_card = self.card(plan, pad=0.22, fill=FILL)
        ident = VGroup(self.txt("FIGURES", 24, BOLD, MUTED), rows, plan_title, plan_card
                       ).arrange(DOWN, aligned_edge=LEFT, buff=0.26)
        ident.next_to(np.array([rx, rtop, 0]), DOWN, buff=0, aligned_edge=UL)
        ident.align_to(np.array([rx, 0, 0]), LEFT).align_to(np.array([0, rtop, 0]), UP)
        self.play(FadeIn(ident[0]), run_time=RUN_QUICK)
        for r in rows:
            self.play(FadeIn(r, shift=RIGHT * 0.08), run_time=RUN_QUICK)
            self.wait(PAUSE_SHORT)
        self.qa_event("signed_classification_complete")
        self.wait(PAUSE_READ)
        self.play(FadeIn(plan_title), FadeIn(plan_card[0]), run_time=RUN_QUICK)
        self.play(Write(plan), run_time=RUN_SLOW)
        self.qa_event("plan")
        self.wait(PAUSE_WORK)
        self.play(FadeOut(ident), run_time=RUN_NORMAL)

        # ---------------- STEP 2 · CALCULATE each figure --------------------
        self.set_subtitle("Step 2 of 4 · CALCULATE: one figure at a time. "
                          "Formula → substitute → area with units.")
        col_x = [rx, rx + 3.40]
        heads = VGroup(self.txt("ADD (+)", 23, BOLD, MUTED), self.txt("SUBTRACT (−)", 23, BOLD, MUTED))
        for h, x in zip(heads, col_x):
            h.move_to(np.array([x, rtop, 0]), aligned_edge=UL)
        ledger_head = heads
        self.play(FadeIn(heads), run_time=RUN_QUICK)
        ledger = VGroup()
        row_step = 0.54
        n_rows = max(len(prob.positives), len(prob.negatives))
        first_y = heads.get_bottom()[1] - 0.18 - 0.22
        ledger_bottom = first_y - (n_rows - 1) * row_step - 0.24
        counters = {+1: 0, -1: 0}
        for part in prob.parts:
            spot = self.spotlight_on(fig, part.key)
            sign_word = "(+)" if part.sign > 0 else "(−)"
            title = self.txt(f"{part.key} · {part.name.upper()} {sign_word}", 23, BOLD)
            eqs = VGroup(*[self.math(e, 33) for e in part.calc_lines()]
                         ).arrange(DOWN, aligned_edge=LEFT, buff=0.18)
            content = VGroup(title, eqs).arrange(DOWN, aligned_edge=LEFT, buff=0.22)
            card = self.card(content, pad=0.22, width=RIGHT_PANEL["w"] - 0.60)
            avail_top = ledger_bottom - 0.20
            avail_bot = rp.get_bottom()[1] + 0.20
            card.move_to(np.array([rp.get_center()[0], (avail_top + avail_bot) / 2, 0]))
            if card.height > avail_top - avail_bot:
                print(f"LAYOUT WARNING: calc card too tall P{prob.number} {part.key}")
                card.align_to(np.array([0, avail_bot, 0]), DOWN)
            self.play(FadeIn(card[0]), FadeIn(title), run_time=RUN_NORMAL)
            for e in eqs:
                self.play(Write(e), run_time=RUN_SLOW)
                self.wait(PAUSE_READ)
            self.qa_event(f"local_calc_{part.key}_{part.name}")
            self.wait(PAUSE_EXPLAIN)
            row = self.ledger_row(part)
            k = counters[part.sign]
            counters[part.sign] += 1
            x = col_x[0] if part.sign > 0 else col_x[1]
            row.move_to(np.array([x, first_y - k * row_step, 0]), aligned_edge=LEFT)
            self.play(FadeOut(card), FadeOut(spot), FadeIn(row, shift=UP * 0.08),
                      run_time=RUN_NORMAL)
            ledger.add(row)
            self.wait(PAUSE_SHORT)
        self.qa_event("all_areas")
        self.wait(PAUSE_READ)

        # ---------------- STEP 3 · COMBINE -----------------------------------
        self.set_subtitle("Step 3 of 4 · COMBINE: add the (+) areas, subtract the (−) areas. "
                          "Keep π exact until the last line.")
        self.play(FadeOut(ledger), FadeOut(ledger_head), run_time=RUN_NORMAL)
        lines = prob.combine_lines()
        eqs = VGroup()
        for j, e in enumerate(lines):
            last = j == len(lines) - 1
            eqs.add(self.math(e, 38 if last else 36, C_POS if last else INK))
        eqs.arrange(DOWN, aligned_edge=LEFT, buff=0.30)
        head = self.txt("COMBINE", 24, BOLD, MUTED)
        block = VGroup(head, eqs).arrange(DOWN, aligned_edge=LEFT, buff=0.30)
        block.move_to(np.array([rx, rtop, 0]), aligned_edge=UL)
        self.play(FadeIn(head), run_time=RUN_QUICK)
        for e in eqs:
            self.play(Write(e), run_time=RUN_SLOW)
            self.wait(PAUSE_READ)
        self.qa_event("final_equation")
        self.wait(PAUSE_WORK)

        # ---------------- STEP 4 · CHECK -------------------------------------
        self.set_subtitle("Step 4 of 4 · CHECK: is the answer reasonable? Are the units "
                          "square units?")
        ans_title = self.txt("ANSWER", 24, BOLD, C_POS)
        ans_eq = self.math(r"A_s=" + (prob.answer.latex() if prob.answer.b == 0 else
                                      prob.answer.latex() + r"\approx " + prob.answer.approx())
                           + r"\ \text{cm}^2", 40, C_POS)
        ans = self.card(VGroup(ans_title, ans_eq).arrange(DOWN, aligned_edge=LEFT, buff=0.18),
                        pad=0.24, stroke=C_POS, sw=2.6, width=RIGHT_PANEL["w"] - 0.60)
        chk_title = self.txt("CHECK", 24, BOLD, C_GAL)
        chk_lines = VGroup(*[self.wrap(c, 23, RIGHT_PANEL["w"] - 1.05) for c in prob.checks]
                           ).arrange(DOWN, aligned_edge=LEFT, buff=0.20)
        chk = self.card(VGroup(chk_title, chk_lines).arrange(DOWN, aligned_edge=LEFT, buff=0.22),
                        pad=0.24, stroke=C_GAL, sw=2.2, width=RIGHT_PANEL["w"] - 0.60)
        VGroup(ans, chk).arrange(DOWN, buff=0.34).move_to(rp)
        self.play(FadeOut(block), run_time=RUN_NORMAL)
        self.play(FadeIn(ans), run_time=RUN_NORMAL)
        self.wait(PAUSE_READ)
        self.play(FadeIn(chk[0]), FadeIn(chk_title), run_time=RUN_QUICK)
        for c in chk_lines:
            self.play(FadeIn(c, shift=RIGHT * 0.06), run_time=RUN_QUICK)
            self.wait(PAUSE_SHORT)
        self.qa_event("check")
        self.read_wait(*prob.checks, extra=PAUSE_EXPLAIN)
        self.clear_all()

    # ======================================================= answer key ====
    def answer_key(self, num: str):
        self.next_section("answer_key")
        self._qa_problem = "answer_key"
        self.set_header(num, "ANSWER KEY",
                        "Compare with your work. Full marks need the method, the exact "
                        "answer and square units.")
        rows = VGroup()
        head = VGroup(self.txt("PROBLEM", 22, BOLD, MUTED), self.txt("FIGURES", 22, BOLD, MUTED),
                      self.txt("SHADED AREA", 22, BOLD, MUTED))
        widths = [4.6, 2.0, 6.6]
        table = []
        for p in PROBLEMS:
            ans = (self.math(rf"{p.answer.latex()}\ \text{{cm}}^2", 38, C_POS)
                   if p.answer.b == 0 else
                   self.math(rf"{p.answer.latex()}\approx {p.answer.approx()}\ \text{{cm}}^2",
                             38, C_POS))
            table.append(VGroup(self.txt(f"{p.number} · {p.title.title()}", 26, BOLD),
                                self.txt(str(p.n_figures), 26), ans))
        all_rows = [head] + table
        y = 1.55
        for r in all_rows:
            x = -6.9
            for cell, w in zip(r, widths):
                cell.move_to(np.array([x, y, 0]), aligned_edge=LEFT)
                x += w
            rows.add(r)
            y -= 1.05 if r is head else 1.10
        lines = VGroup(*[Line(LEFT * 7.0, RIGHT * 7.0, color=RULE, stroke_width=2)
                         .move_to(UP * (1.55 - 0.52 - k * 1.10)) for k in range(3)])
        self.play(FadeIn(rows[0]), FadeIn(lines), run_time=RUN_NORMAL)
        for r in rows[1:]:
            self.play(FadeIn(r, shift=RIGHT * 0.08), run_time=RUN_NORMAL)
            self.wait(PAUSE_READ)
        closing = self.txt("Identify the figures  →  sign each one  →  calculate  →  combine  "
                           "→  check.", 24, BOLD, STROKE)
        closing.to_edge(DOWN, buff=0.55)
        self.play(FadeIn(closing), run_time=RUN_NORMAL)
        self.qa_event("answer_key")
        self.wait(PAUSE_FINAL + PAUSE_WORK)
        good = self.txt("Good luck in Canada!", 30, BOLD, C_GAL).next_to(closing, UP, buff=0.40)
        self.play(FadeIn(good, shift=UP * 0.08), run_time=RUN_NORMAL)
        self.qa_event("closing")
        self.wait(PAUSE_FINAL)
        self.clear_all()
        self.wait(0.6)

    # ========================================================= assembly ====
    def construct(self):
        self.qa_events, self.qa_fails = [], []
        self.header = None
        self._qa_problem = "global"
        log = verify_all()                       # Gate A: fail before rendering
        print("\n".join(log), flush=True)
        self.wait(0.4)                           # white opening frame
        self.cover()
        self.how_it_works()
        self.toolbox()
        n = 3
        for prob in PROBLEMS:
            fig, lp, rp = self.problem_statement(prob, f"{n:02d}")
            self.solution(prob, f"{n + 1:02d}", fig, lp, rp)
            n += 2
        self.answer_key(f"{n:02d}")
        self._write_qa()

    def _write_qa(self):
        out = os.getenv("QA_OUT", "qa")
        os.makedirs(out, exist_ok=True)
        with open(os.path.join(out, "QA_EVENTS.txt"), "w") as f:
            for p, s, t in self.qa_events:
                f.write(f"{p}|{s}|{t:.3f}\n")
        with open(os.path.join(out, "QA_FAILS.txt"), "w") as f:
            f.write("\n".join(self.qa_fails) + ("\n" if self.qa_fails else ""))
        print(f"QA: {len(self.qa_events)} events, {len(self.qa_fails)} audit failures",
              flush=True)
